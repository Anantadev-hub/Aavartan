/** Recycler match-reason chip text ("Accepts PCB", "Nearby — 3 km away", …). */
export function matchReason(lang: Lang, reason: string): string {
  const r = (reason ?? "").trim();
  if (!r) return "";
  const accepts = r.match(/^Accepts\s+(.+)$/i);
  if (accepts) return translateVars(lang, "recyclers.acceptsCode", { code: accepts[1] });
  const nearby = r.match(/^Nearby\s+—\s+(.+?)\s+km away$/i);
  if (nearby) return translateVars(lang, "recyclers.kmAway", { km: nearby[1] });
  const offers = r.match(/^Offers\s+₹([\d,.]+)\/kg$/i);
  if (offers) return translateVars(lang, "recyclers.offersRate", { rate: offers[1] });
  if (/^authorized recycler$/i.test(r)) return translate(lang, "recyclers.authorised");
  if (/^pickup available$/i.test(r)) return translate(lang, "recyclers.pickupAvailable");
  return r;
}

/** Price-board terminology headline. */
export function terminologyHeadline(lang: Lang, headline: string | null | undefined): string {
  const h = (headline ?? "").trim();
  if (!h) return "";
  if (/^demo reference price$/i.test(h)) return translate(lang, "term.demo");
  if (/^latest daily reference price$/i.test(h)) return translate(lang, "term.daily");
  if (/^latest market price$/i.test(h)) return translate(lang, "term.market");
  if (/^latest available reference price$/i.test(h)) return translate(lang, "term.latest");
  return h;
}

/** Price-board terminology note that accompanies the headline. */
export function terminologyNote(lang: Lang, note: string | null | undefined): string {
  const n = (note ?? "").trim();
  if (!n) return "";
  if (/^updated once per day/i.test(n)) return translate(lang, "term.note.daily");
  if (/^fetched from the market-data api$/i.test(n)) return translate(lang, "term.note.market");
  if (/^from a controlled reference feed/i.test(n)) return translate(lang, "term.note.latest");
  if (/^simulated price/i.test(n)) return translate(lang, "term.note.demo");
  return n;
}

/** Payment method code ("cash" | "upi") as a localized label. */
export function paymentMethodLabel(lang: Lang, method: string | null | undefined): string {
  const m = (method ?? "").trim().toLowerCase();
  if (!m) return "";
  if (m === "cash") return translate(lang, "payment.cash");
  if (m === "upi") return translate(lang, "payment.upi");
  return method as string;
}

