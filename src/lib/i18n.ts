const DICTS: Record<Lang, Dict> = { en, hi, mr };

export function translate(lang: Lang, key: string): string {
  return DICTS[lang][key] ?? DICTS.en[key] ?? key;
}

/** Replace `{name}` placeholders with the supplied values. */
export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    vars[name] === undefined ? whole : String(vars[name]),
  );
}

/** `translate` with `{placeholder}` interpolation. */
export function translateVars(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  return interpolate(translate(lang, key), vars);
}

const LANG_KEY = "kc.lang";

export function loadLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v && (LANGS as readonly string[]).includes(v)) return v as Lang;
  } catch {
    /* private mode */
  }
  return "en";
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* private mode */
  }
}

// ---------------------------------------------------------------------------
// Relative time — locale aware (format.timeAgo stays English for logs/tests).
// ---------------------------------------------------------------------------

export function timeAgoLang(lang: Lang, ts: number): string {
  const s = Math.floor((Date.now() - ts) / 1000);
  if (s < 60) return translate(lang, "time.justNow");
  const m = Math.floor(s / 60);
  if (m < 60) return translateVars(lang, "time.minutesAgo", { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return translateVars(lang, "time.hoursAgo", { n: h });
  const d = Math.floor(h / 24);
  return translateVars(lang, d > 1 ? "time.daysAgoPlural" : "time.daysAgo", { n: d });
}

