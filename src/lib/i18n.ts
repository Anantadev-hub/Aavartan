/** Lot timeline event label from its machine code. */
export function timelineEventLabel(lang: Lang, code: string, rejected = false): string {
  switch (code) {
    case "created":
      return translate(lang, "tl.ev.created");
    case "sent":
      return translate(lang, "tl.ev.sent");
    case "quoted":
      return translate(lang, rejected ? "tl.ev.quotedRejected" : "tl.ev.quoted");
    case "handed_over":
      return translate(lang, "tl.ev.handed_over");
    case "payment":
      return translate(lang, "tl.ev.payment");
    default:
      return code;
  }
}

/** Lot timeline event description from the server English text. */
export function timelineEventDescription(
  lang: Lang,
  code: string,
  description: string,
): string {
  const d = (description ?? "").trim();
  if (!d) return "";
  // "₹X/kg agreed" — keep the amount, translate the sentence.
  const rate = d.match(/^₹\s*([\d,.]+)\s*\/kg\s+agreed$/i);
  if (rate) return translateVars(lang, "tl.d.rateAgreed", { rate: rate[1] });
  // "{METHOD} — ₹X"
  const methodAmount = d.match(/^(.+?)\s+—\s+(₹[\d,.]+)$/);
  if (methodAmount) {
    return translateVars(lang, "tl.d.methodAmount", {
      method: translate(lang, methodAmount[1].trim().toLowerCase() === "cash" ? "payment.cash" : "payment.upi"),
      amount: methodAmount[2],
    });
  }
  // "Digital record {ref}"
  const record = d.match(/^Digital record\s+(.+)$/i);
  if (record) return translateVars(lang, "tl.d.digitalRecord", { ref: record[1] });

  const map: Array<[RegExp, string]> = [
    [/captured offline, synced to the platform/i, "tl.d.created"],
    [/registered with a unique reference id/i, "tl.d.sent"],
    [/not sent to any recycler yet/i, "tl.d.notSent"],
    [/waiting for the recycler to review/i, "tl.d.waiting"],
    [/review pending/i, "tl.d.reviewPending"],
    [/waiting for the other side to confirm/i, "tl.d.awaitingOther"],
    [/both sides must confirm/i, "tl.d.bothSides"],
    [/cash or upi after handover/i, "tl.d.cashOrUpi"],
  ];
  for (const [re, key] of map) {
    if (re.test(d)) return translate(lang, key);
  }
  // Rejection reasons and any other user-entered text stay verbatim.
  return d;
}

/** Fair Price Meter wording from the insights query. */
export function meterWording(lang: Lang, wording: string | null | undefined): string {
  const w = (wording ?? "").trim();
  if (!w) return "";
  if (/^within typical range$/i.test(w)) return translate(lang, "meter.within");
  if (/^below recent range$/i.test(w)) return translate(lang, "meter.below");
  if (/^above recent range$/i.test(w)) return translate(lang, "meter.above");
  return w;
}

/** True when the meter wording is the "within typical range" variant. */
export function meterIsWithin(lang: Lang, wording: string | null | undefined): boolean {
  return translate(lang, "meter.within") === meterWording(lang, wording);
}

